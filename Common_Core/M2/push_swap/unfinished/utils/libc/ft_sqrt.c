/** 46341^2 = 2147488281 < INT_MAX = 2147483647 */
int	ft_sqrt(int nb)
{
	int	sqrt;

	if (nb <= 0)
		return (0);
	sqrt = 1;
	while (sqrt * sqrt <= nb && sqrt < 46341)
		++sqrt;
	return (sqrt - 1);
}
